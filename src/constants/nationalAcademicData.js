// Helper functions for easy querying across the application
export const nationalAcademicService = {
  getUniversities() {
    return PARTNER_UNIVERSITIES;
  },

  getUniversityById(id) {
    return PARTNER_UNIVERSITIES.find((u) => u.id === id) || PARTNER_UNIVERSITIES[0];
  },

  getFacultiesByUniversity(universityId) {
    return INSTITUTIONS_REGISTRY.filter((inst) => inst.universityId === universityId);
  },

  getFacultyById(facultyId) {
    return INSTITUTIONS_REGISTRY.find((inst) => inst.id === facultyId) || null;
  },

  getFilieresForFaculty(facultyId) {
    const faculty = this.getFacultyById(facultyId);
    if (!faculty) return [];
    return FACULTY_FILIERES_DEFINITIONS[faculty.filiereCategoryKey] || [];
  },

  getFiliereProgram(filiereId) {
    return FILIERE_PROGRAMS_MAP[filiereId] || null;
  },

  getUesByFiliereAndLevel(filiereId, level) {
    const prog = FILIERE_PROGRAMS_MAP[filiereId];
    if (!prog || !prog.ues) return [];
    // If exact level matches
    if (prog.ues[level]) return prog.ues[level];
    // Otherwise fallback to first available level
    const firstLevel = Object.keys(prog.ues)[0];
    return firstLevel ? prog.ues[firstLevel] : [];
  },

  getResources({ universityId, facultyId, filiereId, niveau, codeUe, category, query }) {
    return INITIAL_NATIONAL_RESOURCES.filter((res) => {
      if (universityId && universityId !== 'ALL' && res.universityId !== universityId) return false;
      if (facultyCodeMatch(res, facultyId)) return false;
      if (filiereId && filiereId !== 'all' && res.filiereId !== filiereId) return false;
      if (niveau && niveau !== 'all' && res.niveau !== niveau) return false;
      if (codeUe && codeUe !== 'all' && res.codeUe !== codeUe) return false;
      if (category && category !== 'all' && res.category !== category) return false;
      if (query && query.trim()) {
        const q = query.toLowerCase().trim();
        const matches =
          res.titre.toLowerCase().includes(q) ||
          res.codeUe.toLowerCase().includes(q) ||
          res.ueTitle.toLowerCase().includes(q) ||
          res.description.toLowerCase().includes(q) ||
          res.universityName.toLowerCase().includes(q) ||
          res.filiereLabel.toLowerCase().includes(q);
        if (!matches) return false;
      }
      return true;
    });
  },

  getStats() {
    return {
      universitiesCount: PARTNER_UNIVERSITIES.length, // 11
      facultiesCount: INSTITUTIONS_REGISTRY.length,   // 76
      totalFilieresCount: 784,
      totalRolesCount: 4, // Étudiant, Délégué, Modérateur, Administrateur
    };
  },
};

function facultyCodeMatch(res, facultyId) {
  if (!facultyId || facultyId === 'all') return false;
  // If institution ID is provided like UY1_FS
  const inst = INSTITUTIONS_REGISTRY.find((i) => i.id === facultyId);
  if (inst) {
    return res.facultyCode !== inst.code;
  }
  return false;
}
